import { describe, expect, it } from 'vitest';
import {
  type GeoLine, type TrackLog, CANDIDATE_LINE_M, closeLoop, distanceM, lineCandidate, lineFromTiming, loopControlLine,
  metersPerDegree, orderSectors, parseTimingLine, parseVbo,
} from '../src/core';

// 走行ログのファイルが無くても動く、計測ラインの候補(案件 3)のテスト

describe('[laptiming] の読み取り', () => {
  it('種別・座標(分 → 度、経度は符号を反転)・名前を読む', () => {
    const tl = parseTimingLine('Start   -7858.394470 +1982.321700 -7858.353983 +1982.343741 ¬ Control line');
    expect(tl?.kind).toBe('start');
    expect(tl!.p1.lat).toBeCloseTo(1982.3217 / 60, 9);
    expect(tl!.p1.lon).toBeCloseTo(7858.39447 / 60, 9);
    expect(tl!.p2.lon).toBeCloseTo(7858.353983 / 60, 9);
    expect(tl!.name).toBe('Control line');
    expect(parseTimingLine('Split -8191.549590 +2090.721700 -8191.518899 +2090.731369 ¬ 鈴鹿Full 5')).toMatchObject({ kind: 'split', name: '鈴鹿Full 5' });
    expect(parseTimingLine('Start 1 2 3')).toBeNull();
  });

  it('.vbo の [session data] の name と [laptiming] を TrackLog に入れる。無ければ入れない', () => {
    const head = 'File created on 06/05/2026 at 00:45:44\r\n\r\n[header]\r\nsatellites\r\n\r\n[comments]\r\nGenerated by RaceChrono\r\n\r\n';
    const data = '[column names]\r\nsats time lat long velocity heading height\r\n\r\n[data]\r\n'
      + '010 004544.00 +01982.3217 -07858.3944 100.0 120.0 +00800.0\r\n010 004544.10 +01982.3218 -07858.3943 100.0 120.0 +00800.0\r\n';
    const withTiming = parseVbo(head + '[session data]\r\nname Autopolis\r\nnotes メモ\r\n\r\n[laptiming]\r\n'
      + 'Start   -7858.394470 +1982.321700 -7858.353983 +1982.343741 ¬ Control line\r\n'
      + 'Split   -7858.574470 +1981.989410 -7858.605481 +1981.996620 ¬ Split 1\r\n\r\n' + data, 'a.vbo');
    expect(withTiming.sessionName).toBe('Autopolis');
    expect(withTiming.laptiming?.map((l) => l.kind)).toEqual(['start', 'split']);
    expect(withTiming.t.length).toBe(2);
    const plain = parseVbo(head + data, 'b.vbo');
    expect(plain.sessionName).toBeUndefined();
    expect(plain.laptiming).toBeUndefined();
  });
});

describe('[laptiming] から作る線', () => {
  it('1 点目を中心に、2 点目 → 1 点目の向きに直交し、長さは 36.8 m。始点は進む向きの左', () => {
    const p1 = { lat: 33, lon: 131 };
    const m = metersPerDegree(33);
    const p2 = { lat: 33 - 50 / m.lat, lon: 131 };                         // 50 m 南 → 北へ進む
    const l = lineFromTiming({ kind: 'start', p1, p2, name: '' });
    expect(distanceM(l.a, l.b)).toBeCloseTo(CANDIDATE_LINE_M, 3);
    expect((l.a.lat + l.b.lat) / 2).toBeCloseTo(33, 9);
    expect((l.a.lon + l.b.lon) / 2).toBeCloseTo(131, 9);
    expect(l.a.lat).toBeCloseTo(33, 9);                                       // 東西方向の線
    expect(l.a.lon).toBeLessThan(l.b.lon);                                   // 北へ進むときの左 = 西
  });
});

// 半径 300 m の円を、反時計回りに 100 km/h・10Hz で走る人工のログ
const C = { lat: 33, lon: 131 };
const R = 300;
const V = 100 / 3.6;
const m = metersPerDegree(C.lat);
const at = (deg: number, r = R) => {
  const a = (deg * Math.PI) / 180;
  return { lat: C.lat + (r * Math.sin(a)) / m.lat, lon: C.lon + (r * Math.cos(a)) / m.lon };
};
function ride(from: number, to: number, r: (deg: number) => number = () => R): TrackLog {
  const step = ((V * 0.1) / R) * (180 / Math.PI);
  const n = Math.floor((to - from) / step) + 1;
  const log: TrackLog = {
    fileName: 'ring.vbo', createdUtc: null, startEpochMs: null, columns: [], comments: [],
    t: new Float64Array(n), lat: new Float64Array(n), lon: new Float64Array(n), speed: new Float64Array(n),
  };
  for (let i = 0; i < n; i++) {
    const deg = from + i * step;
    const p = at(deg, r(deg));
    log.t[i] = i * 0.1; log.lat[i] = p.lat; log.lon[i] = p.lon; log.speed[i] = 100;
  }
  return log;
}
/** 線の向き(線そのものの方位、0〜180°) */
const lineDeg = (l: GeoLine) => {
  const dx = (l.b.lon - l.a.lon) * m.lon, dy = (l.b.lat - l.a.lat) * m.lat;
  return ((Math.atan2(dx, dy) * 180) / Math.PI + 180) % 180;
};

describe('1 周分のログ(輪)から作る計測ライン', () => {
  it('輪でないログ(closeLoop していない)では作らない', () => {
    expect(loopControlLine(ride(0, 300))).toBeNull();
    expect(lineCandidate(ride(0, 300))).toBeNull();
  });

  it('始点と終点が近いときは、前後の進む向きの平均に直交する(円の 0° の位置なら東西の線)', () => {
    const log = closeLoop(ride(0, 360));
    expect(log.loop).toBeTruthy();
    const l = loopControlLine(log)!;
    expect(distanceM(l.a, l.b)).toBeCloseTo(CANDIDATE_LINE_M, 3);
    const mid = { lat: (l.a.lat + l.b.lat) / 2, lon: (l.a.lon + l.b.lon) / 2 };
    expect(distanceM(mid, at(0))).toBeLessThan(2);
    expect(Math.abs(lineDeg(l) - 90)).toBeLessThan(1);                        // 東西(0° の位置では北へ進む)
    // 0° の位置では北へ進む(反時計回り)。左 = 西 = 円の内側
    expect(distanceM(l.a, C)).toBeLessThan(distanceM(l.b, C));
    const c = lineCandidate(log)!;
    expect(c.source).toBe('loop');
    expect(c.sectors).toEqual([]);
  });

  it('始点と終点が 5 m 以上離れているときは、2 点を結んだ線の向きを使う', () => {
    // 始点は外側(半径 + 4 m)、終点は内側(半径 − 4 m)に寄せる → 2 点は 8 m 離れて、計測線は斜めでなく円の半径の向き
    const log = closeLoop(ride(0, 360, (deg) => (deg < 30 ? R + 4 : deg > 330 ? R - 4 : R)));
    const l = loopControlLine(log)!;
    const s = { lat: log.lat[0], lon: log.lon[0] }, e = { lat: log.lat[log.loop!.n - 1], lon: log.lon[log.loop!.n - 1] };
    expect(distanceM(s, e)).toBeGreaterThan(5);
    expect(Math.abs(lineDeg(l) - lineDeg({ a: e, b: s }))).toBeLessThan(0.5);
  });
});

describe('セクターの並べ替え', () => {
  it('計測ラインから始まる 1 周の中で通る順に並べ、通らないものは最後に置く', () => {
    const log = ride(0, 800);
    const cross = (deg: number): GeoLine => ({ a: at(deg, R - 10), b: at(deg, R + 10) });
    const far: GeoLine = { a: { lat: 34, lon: 132 }, b: { lat: 34.001, lon: 132 } };
    const s = [cross(200), far, cross(90), cross(300)];
    expect(orderSectors(log, cross(45), s)).toEqual([s[2], s[0], s[3], s[1]]);
  });
});
